// кратчайшая разница на замкнутой оси: мир без стен, края сшиты
function wrapD(d, s){ return ((d % s) + s*1.5) % s - s/2; }
function wrap(v, s){ return ((v % s) + s) % s; }
function dist(ax,ay,bx,by){ return Math.hypot(wrapD(ax-bx,W), wrapD(ay-by,H)); }
function zd(a, b){ return wrapD(a - b, 1); }        // разница глубин по кольцу слоёв

